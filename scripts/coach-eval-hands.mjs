const rankValues = { T: 10, J: 11, Q: 12, K: 13, A: 14 };
const suitValues = { c: 'clubs', d: 'diamonds', h: 'hearts', s: 'spades' };

function cardFromCode(code) {
  const rankToken = code.slice(0, -1).toUpperCase();
  return {
    rank: Number(rankToken) || rankValues[rankToken],
    suit: suitValues[code.slice(-1).toLowerCase()],
  };
}

function verifiedCallInput({ heroCards, board, potBefore, toCall, stack = 300, bigBlind = 2 }) {
  const street = board.length === 3 ? 'flop' : board.length === 4 ? 'turn' : 'river';
  const canRaise = stack > toCall;
  return {
    version: 1,
    bigBlind,
    heroCards: heroCards.map(cardFromCode),
    board: board.map(cardFromCode),
    decisions: [{
      action: 'call',
      amount: toCall,
      street,
      board: board.map(cardFromCode),
      potBefore,
      currentBet: toCall,
      toCall,
      heroStackBefore: stack,
      opponentStackBefore: stack,
      heroStreetBetBefore: 0,
      opponentStreetBetBefore: toCall,
      legalActions: {
        canFold: true,
        canCheck: false,
        canCall: true,
        canRaise,
        toCall,
        minRaiseTo: canRaise ? Math.min(stack, toCall * 2) : 0,
        maxRaiseTo: canRaise ? stack : 0,
        suggestedRaiseTo: canRaise ? Math.min(stack, toCall * 2.5) : 0,
      },
    }],
  };
}

